-- ICT371 QUESTION 6: MONTHLY PAYROLL PROCESSING

DROP VIEW IF EXISTS v_payroll_report CASCADE;
DROP TABLE IF EXISTS salary_audit, payroll, employees CASCADE;

CREATE TABLE employees (
    employee_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    basic_salary NUMERIC(12,2) NOT NULL CHECK (basic_salary >= 0),
    allowance NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (allowance >= 0),
    deduction NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (deduction >= 0),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE payroll (
    payroll_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL REFERENCES employees(employee_id),
    pay_month DATE NOT NULL CHECK (EXTRACT(DAY FROM pay_month) = 1),
    gross_pay NUMERIC(12,2) NOT NULL CHECK (gross_pay >= 0),
    net_pay NUMERIC(12,2) NOT NULL CHECK (net_pay >= 0),
    UNIQUE(employee_id, pay_month)
);

CREATE TABLE salary_audit (
    audit_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL REFERENCES employees(employee_id),
    old_salary NUMERIC(12,2) NOT NULL,
    new_salary NUMERIC(12,2) NOT NULL,
    changed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- (d) Audit actual basic salary changes.
CREATE OR REPLACE FUNCTION fn_audit_salary_change()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.basic_salary IS DISTINCT FROM NEW.basic_salary THEN
        INSERT INTO salary_audit(employee_id, old_salary, new_salary)
        VALUES (NEW.employee_id, OLD.basic_salary, NEW.basic_salary);
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_salary_audit
AFTER UPDATE OF basic_salary ON employees
FOR EACH ROW EXECUTE FUNCTION fn_audit_salary_change();

-- (b) Current net pay function.
CREATE OR REPLACE FUNCTION fn_net_pay(p_employee_id INTEGER)
RETURNS NUMERIC(12,2) LANGUAGE plpgsql AS $$
DECLARE
    v_basic NUMERIC(12,2); v_allowance NUMERIC(12,2); v_deduction NUMERIC(12,2);
    v_net NUMERIC(12,2);
BEGIN
    SELECT basic_salary, allowance, deduction
    INTO v_basic, v_allowance, v_deduction
    FROM employees WHERE employee_id = p_employee_id;

    IF NOT FOUND THEN RAISE EXCEPTION 'Unknown employee ID: %', p_employee_id; END IF;

    v_net := v_basic + v_allowance - v_deduction;
    IF v_net < 0 THEN RAISE EXCEPTION 'Computed net pay cannot be negative'; END IF;
    RETURN v_net;
END;
$$;

-- (c) Query FOR loop; existing employee/month rows are left unchanged.
CREATE OR REPLACE PROCEDURE pr_process_payroll(p_month DATE)
LANGUAGE plpgsql AS $$
DECLARE
    r RECORD;
    v_gross NUMERIC(12,2);
    v_net NUMERIC(12,2);
BEGIN
    IF p_month IS NULL OR EXTRACT(DAY FROM p_month) <> 1 THEN
        RAISE EXCEPTION 'Pay month must be the first day of a month';
    END IF;

    FOR r IN SELECT employee_id, basic_salary, allowance
             FROM employees WHERE active = TRUE
             ORDER BY employee_id
    LOOP
        v_gross := r.basic_salary + r.allowance;
        v_net := fn_net_pay(r.employee_id);

        INSERT INTO payroll(employee_id, pay_month, gross_pay, net_pay)
        VALUES (r.employee_id, p_month, v_gross, v_net)
        ON CONFLICT (employee_id, pay_month) DO NOTHING;
    END LOOP;
END;
$$;

