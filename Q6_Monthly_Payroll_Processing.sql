-- (e) Historical payroll remains visible even if employee later becomes inactive.
CREATE OR REPLACE VIEW v_payroll_report AS
SELECT e.full_name, p.pay_month, p.gross_pay, p.net_pay
FROM payroll p
JOIN employees e ON e.employee_id = p.employee_id;

SELECT * FROM v_payroll_report ORDER BY pay_month, full_name;

-- (f) Pay-month index; employee/month unique index does not lead with pay_month.
CREATE INDEX idx_payroll_pay_month ON payroll(pay_month);

